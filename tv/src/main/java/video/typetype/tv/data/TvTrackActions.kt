package video.typetype.tv.data

import androidx.lifecycle.viewModelScope
import kotlinx.coroutines.launch
import video.typetype.sdk.core.PlaybackOpenRequest
import video.typetype.sdk.core.ServiceId
import video.typetype.sdk.core.SubtitleTrack
import video.typetype.sdk.core.TypeTypeResult

public fun TvViewModel.switchVideoTrack(itag: Int, positionMilliseconds: Long) {
    val state = mutableState.value
    val stream = state.stream ?: return
    val video = state.selectedVideo ?: return
    val tracks = stream.selectTvPlaybackTracks(
        isVideoSupported,
        preferredVideoItag = itag,
        preferredAudioItag = state.selectedAudioItag,
        preferredAudioTrackId = state.selectedAudioTrackId,
    ) ?: return
    reopenPlayback(
        video,
        tracks.video.itag,
        tracks.audio.itag,
        tracks.audio.audioTrackId,
        state.subtitleTrack(),
        positionMilliseconds,
    )
}

